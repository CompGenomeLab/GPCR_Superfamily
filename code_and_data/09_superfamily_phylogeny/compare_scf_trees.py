#!/usr/bin/env python3
"""
compare_scf_trees.py - compare per-tree sCF summaries between any number of datasets and plot.

Reads the TSV written by gather_scf.py (one row per tree per stratum), summarises every
dataset at each stratum, compares every pair of datasets, and draws a grouped boxplot.

    python compare_scf_trees.py scf_per_tree_summary.tsv \
           --out-stats scf_tree_stats.tsv --out-pairs scf_tree_pairwise.tsv \
           --out-fig scf_tree_comparison --labels "label 1" "label 2" ...

--labels are given in the order the datasets appear in the summary TSV (the order of the
directories passed to gather_scf.py). Without them the directory names are used.

Statistics are computed with the standard library only. matplotlib is used for the
figure; if it is not installed the statistics are still written and only the plot is
skipped, so this runs on a cluster without a plotting stack.

IMPORTANT - what the p-value means here
    The 100 trees per dataset are ML search replicates on ONE alignment. They are not
    independent samples, so a Mann-Whitney test across them is ANTICONSERVATIVE: it
    will report a very small p even for a modest difference. It is printed because it
    is asked for, but the honest reading of this analysis is whether two
    distributions of per-tree means SEPARATE - i.e. whether the between-dataset
    difference exceeds the spread generated by topology uncertainty. The overlap
    columns and Cohen's d answer that; the p-value does not.

sCF noise floor is ~33% (three possible quartet resolutions).
"""
import os, sys, math, argparse, statistics as st
from collections import defaultdict

# (key, ascii label for console/TSV, unicode label for the figure)
STRATA = [("all",  "All branches", "All branches"),
          ("fam2", ">=2 families", "≥2 families"),
          ("fam3", ">=3 families", "≥3 families"),
          ("fam4", ">=4 families", "≥4 families")]
NOISE = 33.0
# validated categorical slots 1-5 (fixed order, one per dataset)
COLORS = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4"]
INK, INK2, GRID = "#0b0b0b", "#52514e", "#dcdcd8"


def mann_whitney(x, y):
    """Two-sided Mann-Whitney U with tie-corrected normal approximation."""
    a = sorted([(v, 0) for v in x] + [(v, 1) for v in y])
    rs, i, n = [0.0, 0.0], 0, len(a)
    ties = 0.0
    while i < n:
        j = i
        while j + 1 < n and a[j + 1][0] == a[i][0]:
            j += 1
        r = (i + j) / 2.0 + 1
        t = j - i + 1
        ties += t ** 3 - t
        for k in range(i, j + 1):
            rs[a[k][1]] += r
        i = j + 1
    n1, n2 = len(x), len(y)
    U1 = rs[0] - n1 * (n1 + 1) / 2.0
    U = min(U1, n1 * n2 - U1)
    mu = n1 * n2 / 2.0
    N = n1 + n2
    sd = math.sqrt((n1 * n2 / 12.0) * ((N + 1) - ties / (N * (N - 1))))
    if sd == 0:
        return U, 0.0, 1.0, 0.0
    z = (U - mu) / sd
    p = math.erfc(abs(z) / math.sqrt(2))
    rb = 1 - 2 * U / (n1 * n2)          # rank-biserial effect size
    return U, z, p, rb


def cohens_d(x, y):
    nx, ny = len(x), len(y)
    if nx < 2 or ny < 2:
        return float('nan')
    vx, vy = st.variance(x), st.variance(y)
    sp = math.sqrt(((nx - 1) * vx + (ny - 1) * vy) / (nx + ny - 2))
    return (st.mean(y) - st.mean(x)) / sp if sp else float('nan')


def load(path):
    data = defaultdict(lambda: defaultdict(list))     # dataset -> stratum -> [mean]
    nbr = defaultdict(lambda: defaultdict(list))
    with open(path, encoding='utf-8') as fh:
        hdr = fh.readline().rstrip('\n').split('\t')
        ix = {c: i for i, c in enumerate(hdr)}
        for line in fh:
            if not line.strip():
                continue
            p = line.rstrip('\n').split('\t')
            data[p[ix['dataset']]][p[ix['stratum']]].append(float(p[ix['mean_sCF']]))
            nbr[p[ix['dataset']]][p[ix['stratum']]].append(int(p[ix['n_branches']]))
    return data, nbr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('summary', help='TSV from gather_scf.py')
    ap.add_argument('--out-stats', default='scf_tree_stats.tsv')
    ap.add_argument('--out-pairs', default='scf_tree_pairwise.tsv')
    ap.add_argument('--out-fig', default='scf_tree_comparison',
                    help='basename; .svg and .png are written')
    ap.add_argument('--labels', nargs='*', default=None)
    args = ap.parse_args()

    data, nbr = load(args.summary)
    names = list(data)
    if args.labels and len(args.labels) != len(names):
        sys.exit(f"{len(args.labels)} labels given for {len(names)} datasets: {names}")
    LAB = dict(zip(names, args.labels or names))
    if len(names) > len(COLORS):
        sys.exit(f"at most {len(COLORS)} datasets can be plotted, found {len(names)}")

    # ------------------------------------------------ per-dataset summary
    per = []
    for key, nice, fignice in STRATA:
        for ds in names:
            v = data[ds].get(key, [])
            if not v:
                continue
            per.append(dict(stratum=key, nice=nice, ds=ds, n=len(v), mean=st.mean(v),
                            sd=st.stdev(v) if len(v) > 1 else 0.0, med=st.median(v),
                            min=min(v), max=max(v), br=st.mean(nbr[ds][key])))
    with open(args.out_stats, 'w', encoding='utf-8', newline='') as fh:
        fh.write("stratum\tdataset\tlabel\tn_trees\tbranches_per_tree\tmean\tsd\tmedian\tmin\tmax\n")
        for r in per:
            fh.write(f"{r['stratum']}\t{r['ds']}\t{LAB[r['ds']]}\t{r['n']}\t{r['br']:.1f}\t"
                     f"{r['mean']:.3f}\t{r['sd']:.3f}\t{r['med']:.3f}\t{r['min']:.3f}\t{r['max']:.3f}\n")
    print(f"wrote {args.out_stats}\n")

    print(f"{'stratum':>12} {'dataset':<36} {'trees':>5} {'branches/tree':>14} {'mean+-SD':>16} {'range':>15}")
    for r in per:
        print(f"{r['nice']:>12} {LAB[r['ds']][:36]:<36} {r['n']:>5} {r['br']:>14.1f} "
              f"{r['mean']:>8.2f} +- {r['sd']:<5.2f} {r['min']:>7.2f}-{r['max']:<7.2f}")

    # ------------------------------------------------ every pair of datasets
    pairs = []
    for key, nice, fignice in STRATA:
        for a in range(len(names)):
            for b in range(a + 1, len(names)):
                A, B = data[names[a]].get(key, []), data[names[b]].get(key, [])
                if not A or not B:
                    continue
                U, z, p, rb = mann_whitney(A, B)
                overlap = not (max(A) < min(B) or max(B) < min(A))
                pairs.append(dict(stratum=key, nice=nice, A=names[a], B=names[b],
                                  diff=st.mean(B) - st.mean(A), d=cohens_d(A, B),
                                  rb=rb, z=z, p=p, overlap=overlap))
    with open(args.out_pairs, 'w', encoding='utf-8', newline='') as fh:
        fh.write("stratum\tdataset_A\tdataset_B\tlabel_A\tlabel_B\tmean_diff_B_minus_A\t"
                 "cohens_d\trank_biserial\tMW_z\tMW_p\tdistributions_overlap\n")
        for r in pairs:
            fh.write(f"{r['stratum']}\t{r['A']}\t{r['B']}\t{LAB[r['A']]}\t{LAB[r['B']]}\t"
                     f"{r['diff']:+.3f}\t{r['d']:+.3f}\t{r['rb']:+.3f}\t{r['z']:.3f}\t"
                     f"{r['p']:.3g}\t{'yes' if r['overlap'] else 'NO'}\n")
    print(f"\nwrote {args.out_pairs}")
    print("\nNOTE  the 100 trees per dataset are search replicates on one alignment and are")
    print("      NOT independent, so the Mann-Whitney p is anticonservative. The column that")
    print("      matters is 'overlap': NO means the between-dataset difference exceeds the")
    print("      spread produced by topology uncertainty.")
    for r in pairs:
        if not r['overlap']:
            print(f"      -> {r['nice']}: {LAB[r['A']]} vs {LAB[r['B']]} separate completely "
                  f"(mean diff {r['diff']:+.2f})")

    # ------------------------------------------------------------------ figure
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        import matplotlib.patches as mpatches
        import random
    except ImportError:
        print("\n(matplotlib not available - statistics written, figure skipped)")
        return

    keys = [k for k, _, _ in STRATA if any(data[ds].get(k) for ds in names)]
    fignames = {k: f for k, _, f in STRATA}
    n = len(names)
    w = 0.8 / n
    offs = [(j - (n - 1) / 2) * w for j in range(n)]

    fig, ax = plt.subplots(figsize=(max(10.2, 2.4 * len(keys) * n / 2), 6.0))
    fig.patch.set_facecolor("white")
    pos, series, cols = [], [], []
    for i, k in enumerate(keys):
        for j, ds in enumerate(names):
            v = data[ds].get(k, [])
            if not v:
                continue
            pos.append(i + offs[j]); series.append(v); cols.append(COLORS[j])
    bp = ax.boxplot(series, positions=pos, widths=w * 0.8, patch_artist=True,
                    showfliers=False, medianprops=dict(color="white", lw=2.0),
                    whiskerprops=dict(color=INK2, lw=1.2),
                    capprops=dict(color=INK2, lw=1.2), boxprops=dict(lw=0))
    for patch, c in zip(bp['boxes'], cols):
        patch.set_facecolor(c); patch.set_edgecolor("white"); patch.set_linewidth(2)

    random.seed(11)
    for x, v, c in zip(pos, series, cols):
        ax.scatter([x + random.uniform(-w * 0.25, w * 0.25) for _ in v], v,
                   s=7, color=c, alpha=0.35, linewidths=0, zorder=3)

    ax.axhline(NOISE, ls=(0, (5, 4)), lw=1.4, color="#8a8a84", zorder=0)
    lo = min(min(s) for s in series); hi = max(max(s) for s in series)
    span = hi - lo or 1.0
    ax.set_ylim(min(lo - 0.25 * span, NOISE - 1), hi + 0.15 * span)
    ax.text(-0.52, NOISE - 0.03 * span, "noise floor 33%", va="top", ha="left",
            fontsize=9.5, color=INK2)

    ax.set_xticks(range(len(keys)))
    ax.set_xticklabels([fignames[k] for k in keys], fontsize=10.5, color=INK)
    ax.set_xlim(-0.55, len(keys) - 0.45)
    ax.set_ylabel("Mean site concordance factor per tree (%)", fontsize=11, color=INK)
    ax.yaxis.grid(True, color=GRID, lw=0.8); ax.set_axisbelow(True)
    for s in ("top", "right", "bottom"):
        ax.spines[s].set_visible(False)
    ax.spines["left"].set_color(GRID)
    ax.tick_params(axis="y", colors=INK2, length=0, labelsize=10)
    ax.tick_params(axis="x", length=0)
    ntr = {ds: max(len(v) for v in data[ds].values()) for ds in names}
    ax.legend(handles=[mpatches.Patch(color=COLORS[j], label=f"{LAB[ds]}  (n={ntr[ds]} trees)")
                       for j, ds in enumerate(names)],
              loc="upper center", bbox_to_anchor=(0.5, -0.08), ncol=min(n, 3), frameon=False,
              fontsize=10, labelcolor=INK)
    fig.suptitle("Site concordance across 100 ML trees per dataset",
                 fontsize=13.5, color=INK, x=0.045, ha="left", y=0.985)
    fig.text(0.045, 0.930, "Each point is one ML tree, summarised as its mean sCF over the branches in that stratum.",
             fontsize=9.5, color=INK2, ha="left")
    fig.text(0.045, 0.898, "A family counts toward a branch only if the branch holds >50% of that family's leaves.",
             fontsize=9.5, color=INK2, ha="left")
    fig.tight_layout(rect=[0, 0.02, 1, 0.865])
    for ext in ("svg", "png"):
        fig.savefig(f"{args.out_fig}.{ext}", dpi=200, facecolor="white", bbox_inches="tight")
    print(f"\nwrote {args.out_fig}.svg / .png")


if __name__ == '__main__':
    main()
